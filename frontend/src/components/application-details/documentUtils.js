function jmlShouldPass(appName, scenario) {
  let hash = 0;
  const s = appName + scenario;
  for (let i = 0; i < s.length; i++) hash = (hash * 31 + s.charCodeAt(i)) >>> 0;
  return hash % 10 < 8;
}
